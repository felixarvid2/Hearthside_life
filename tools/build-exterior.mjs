#!/usr/bin/env node
// Builds the Milestone 9 garden and staircase models (tools/exterior) into public/assets/furniture, merges them into
// public/assets/manifest.json (entries flagged `exterior`, which tools/build-extra-furniture.mjs leaves alone) and writes
// src/content/exteriorModels.ts (the measured model bounds that content/exteriorObjects.ts fits the models with).
// Usage: node tools/build-exterior.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildExterior } from './exterior/index.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'public', 'assets');
const manifestFile = path.join(OUT, 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
const entries = await buildExterior(OUT);
for (const [name, entry] of Object.entries(manifest.furniture)) if (entry.exterior && !entries[name]) delete manifest.furniture[name];
Object.assign(manifest.furniture, entries);
manifest.sources.furnitureExterior = 'Original low-poly garden and staircase models built by tools/exterior (this project, CC0)';
fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 1));

const lines = Object.entries(entries).map(([name, e]) => `  ${name}: [[${e.min.join(', ')}], [${e.max.join(', ')}]],`);
fs.writeFileSync(path.join(ROOT, 'src', 'content', 'exteriorModels.ts'), [
  '// GENERATED by tools/build-exterior.mjs (node tools/build-exterior.mjs). Measured bounds [min, max] of the exterior models, in the',
  '// units of the GLB files (half-scale metres); content/exteriorObjects.ts fits them into their footprints. Do not edit.',
  '',
  'export const EXTERIOR_BOUNDS: Record<string, [min: [number, number, number], max: [number, number, number]]> = {',
  ...lines, '};', '',
].join('\n'));
console.log(`manifest: ${Object.keys(entries).length} exterior models`);
