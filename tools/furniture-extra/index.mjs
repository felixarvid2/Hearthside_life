// Original furniture pipeline step: builds the models of models.mjs as GLBs in public/assets/furniture, renders their
// catalog thumbnails and returns manifest entries (bounds and materials measured from the written file, like the Kenney
// models). build-assets.mjs calls it after the Kenney copy; `node tools/build-extra-furniture.mjs` runs it alone and merges
// the entries into the existing manifest.
//
// Milestone 10 models (m10/<group>.mjs) also get their measured data written to src/content/objectsM10/<group>.models.ts
// (bounds for MODEL_BOUNDS and, for models with an `anim:screen` part, the picture rectangle), so nobody types them by hand.

import { NodeIO } from '@gltf-transform/core';
import { getBounds } from '@gltf-transform/functions';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXTRA_MODELS, MODEL_GROUPS, MODEL_GROUP_OF, buildModels } from './models.mjs';
import { renderThumb } from './thumb.mjs';

export const EXTRA_SOURCE = 'Original low-poly models generated by tools/furniture-extra (this project, CC0), same materials and conventions as the Kenney Furniture Kit';

const CONTENT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'src', 'content', 'objectsM10');

/** The LICENSES.md table row for the original models, generated from the registry (no hand-kept list). */
export function extraFurnitureLicenseRow() {
  return `| furniture/ (${Object.keys(EXTRA_MODELS).join(', ')}) | Original low-poly models and thumbnails built by tools/furniture-extra for this project, in the kit's style and materials | CC0 1.0 |`;
}

/** The generated src/content/objectsM10/<group>.models.ts text for one group's entries. */
function modelsTs(group, entries) {
  const lines = [
    `// GENERATED by tools/build-extra-furniture.mjs from tools/furniture-extra/m10/${group}.mjs - do not edit by hand.`,
    '// Measured from the written GLBs (same numbers as public/assets/manifest.json): model bounds for MODEL_BOUNDS and the picture',
    '// rectangle of models with an `anim:screen` part.',
    "import type { M10ModelInfo } from './modelInfo';",
    '',
    `export const MODELS: Record<string, M10ModelInfo> = {`,
  ];
  for (const [name, e] of Object.entries(entries).sort(([a], [b]) => (a < b ? -1 : 1))) {
    const v = (a) => `[${a.join(', ')}]`;
    const screen = e.screen ? `, screen: { centre: ${v(e.screen.centre)}, normal: ${v(e.screen.normal)}, width: ${e.screen.width}, height: ${e.screen.height} }` : '';
    lines.push(`  ${name}: { bounds: [${v(e.min)}, ${v(e.max)}]${screen} },`);
  }
  lines.push('};', '');
  return lines.join('\n');
}

/**
 * Writes GLBs and thumbnails under outDir (public/assets) and returns { assetName: manifestEntry }. `only` limits the run to
 * one group ('base' or a file name of m10/); the content data of the built Milestone 10 groups is written either way.
 */
export async function buildExtraFurniture(outDir, { only, contentData = true } = {}) {
  const io = new NodeIO();
  fs.mkdirSync(path.join(outDir, 'furniture', 'thumbs'), { recursive: true });
  const entries = {};
  const r = (v) => v.map((x) => +x.toFixed(4));
  for (const [name, model] of Object.entries(buildModels(only))) {
    const glb = await model.toGlb(io);
    const file = path.join(outDir, 'furniture', `${name}.glb`);
    fs.writeFileSync(file, glb);
    const doc = await io.readBinary(glb);
    const bounds = getBounds(doc.getRoot().listScenes()[0]);
    const materials = doc.getRoot().listMaterials().map((m) => ({ name: m.getName(), color: m.getBaseColorFactor().slice(0, 3).map((v) => +v.toFixed(3)) }));
    fs.writeFileSync(path.join(outDir, 'furniture', 'thumbs', `${name}.png`), await renderThumb(model.scaledTriangles()));
    const group = MODEL_GROUP_OF[name];
    entries[name] = { file: `furniture/${name}.glb`, thumb: `furniture/thumbs/${name}.png`, min: r(bounds.min), max: r(bounds.max), materials, original: true };
    if (group !== 'base') entries[name].group = group;
    if (model.parts.size) entries[name].animNodes = model.partNames();
    const screen = model.screenQuad();
    if (screen) entries[name].screen = screen;
    console.log(`extra furniture ${name}: ${model.triangleCount()} triangles, ${(glb.length / 1024).toFixed(1)} KB`);
  }
  if (contentData) {
    fs.mkdirSync(CONTENT_DIR, { recursive: true });
    for (const group of Object.keys(MODEL_GROUPS)) {
      if (group === 'base' || (only !== undefined && only !== group)) continue;
      const mine = Object.fromEntries(Object.entries(entries).filter(([name]) => MODEL_GROUP_OF[name] === group));
      const file = path.join(CONTENT_DIR, `${group}.models.ts`);
      const text = modelsTs(group, mine);
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
    }
  }
  return entries;
}
