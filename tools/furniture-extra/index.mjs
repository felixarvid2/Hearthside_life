// Original furniture pipeline step: builds the models of models.mjs as GLBs in public/assets/furniture, renders their
// catalog thumbnails and returns manifest entries (bounds and materials measured from the written file, like the Kenney
// models). build-assets.mjs calls it after the Kenney copy; `node tools/build-extra-furniture.mjs` runs it alone and merges
// the entries into the existing manifest.

import { NodeIO } from '@gltf-transform/core';
import { getBounds } from '@gltf-transform/functions';
import fs from 'node:fs';
import path from 'node:path';
import { buildModels } from './models.mjs';
import { renderThumb } from './thumb.mjs';

export const EXTRA_SOURCE = 'Original low-poly models generated by tools/furniture-extra (this project, CC0), same materials and conventions as the Kenney Furniture Kit';

/** Writes GLBs and thumbnails under outDir (public/assets) and returns { assetName: manifestEntry }. */
export async function buildExtraFurniture(outDir) {
  const io = new NodeIO();
  fs.mkdirSync(path.join(outDir, 'furniture', 'thumbs'), { recursive: true });
  const entries = {};
  const r = (v) => v.map((x) => +x.toFixed(4));
  for (const [name, model] of Object.entries(buildModels())) {
    const glb = await model.toGlb(io);
    const file = path.join(outDir, 'furniture', `${name}.glb`);
    fs.writeFileSync(file, glb);
    const doc = await io.readBinary(glb);
    const bounds = getBounds(doc.getRoot().listScenes()[0]);
    const materials = doc.getRoot().listMaterials().map((m) => ({ name: m.getName(), color: m.getBaseColorFactor().slice(0, 3).map((v) => +v.toFixed(3)) }));
    fs.writeFileSync(path.join(outDir, 'furniture', 'thumbs', `${name}.png`), await renderThumb(model.scaledTriangles()));
    entries[name] = { file: `furniture/${name}.glb`, thumb: `furniture/thumbs/${name}.png`, min: r(bounds.min), max: r(bounds.max), materials, original: true };
    console.log(`extra furniture ${name}: ${model.triangleCount()} triangles, ${(glb.length / 1024).toFixed(1)} KB`);
  }
  return entries;
}
