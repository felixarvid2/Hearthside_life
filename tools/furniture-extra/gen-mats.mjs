#!/usr/bin/env node
// Writes the MATS table (each model's materials, biggest surface first) into src/content/objectsM10/<group>.ts, between the
// `// MATS:BEGIN` and `// MATS:END` markers, so finish regions can name only materials the model really has.
// Usage: node tools/furniture-extra/gen-mats.mjs --group=seating-beds   (touches only that group's content file)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const group = process.argv.slice(2).find((a) => a.startsWith('--group='))?.slice(8);
if (!group || !/^[a-z-]+$/.test(group)) { console.error('usage: gen-mats.mjs --group=<group>'); process.exit(1); }
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const models = (await import(`./m10/${group}.mjs`)).default;
const lines = [];
for (const [name, build] of Object.entries(models)) {
  const area = {};
  for (const t of build().scaledTriangles()) {
    const [a, b, c] = t.p;
    const u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]], v = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
    area[t.mat] = (area[t.mat] ?? 0) + Math.hypot(u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]) / 2;
  }
  lines.push(`  ${name}: [${Object.entries(area).sort((x, y) => y[1] - x[1]).map(([k]) => `'${k}'`).join(', ')}],`);
}
const file = path.join(root, 'src', 'content', 'objectsM10', `${group}.ts`);
const src = fs.readFileSync(file, 'utf8');
if (!/\/\/ MATS:BEGIN[\s\S]*\/\/ MATS:END/.test(src)) { console.error(`${file}: no MATS:BEGIN/MATS:END block`); process.exit(1); }
fs.writeFileSync(file, src.replace(/\/\/ MATS:BEGIN[\s\S]*\/\/ MATS:END/, `// MATS:BEGIN (generated by tools/furniture-extra/gen-mats.mjs)\nconst MATS: Record<string, string[]> = {\n${lines.join('\n')}\n};\n// MATS:END`));
console.log(`${group}: ${lines.length} models`);
