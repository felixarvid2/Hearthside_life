// Exterior model pipeline (Milestone 9): builds the garden and staircase models of this folder as GLBs in public/assets/furniture
// (the same place, conventions and manifest as tools/furniture-extra), renders their catalog thumbnails and returns manifest
// entries. `node tools/build-exterior.mjs` runs it and merges the entries into public/assets/manifest.json; it also writes
// src/content/exteriorModels.ts with the measured model bounds, which the content uses to fit the models into their footprints.

import { NodeIO } from '@gltf-transform/core';
import { getBounds } from '@gltf-transform/functions';
import fs from 'node:fs';
import path from 'node:path';
import { renderThumb } from '../furniture-extra/thumb.mjs';
import { GARDEN_MODELS } from './garden.mjs';
import { STAIR_MODELS } from './stairs.mjs';

export const EXTERIOR_SOURCE = 'Original low-poly garden and staircase models generated by tools/exterior (this project, CC0)';

export function buildExteriorModels() {
  const out = {};
  for (const [name, make] of Object.entries({ ...GARDEN_MODELS, ...STAIR_MODELS })) { const m = make(); m.id = name; out[name] = m; }
  return out;
}

/** Writes GLBs and thumbnails under outDir (public/assets) and returns { assetName: manifestEntry }. */
export async function buildExterior(outDir) {
  const io = new NodeIO();
  fs.mkdirSync(path.join(outDir, 'furniture', 'thumbs'), { recursive: true });
  const entries = {};
  const r = (v) => v.map((x) => +x.toFixed(4));
  for (const [name, model] of Object.entries(buildExteriorModels())) {
    const glb = await model.toGlb(io);
    fs.writeFileSync(path.join(outDir, 'furniture', `${name}.glb`), glb);
    const doc = await io.readBinary(glb);
    const bounds = getBounds(doc.getRoot().listScenes()[0]);
    const materials = doc.getRoot().listMaterials().map((m) => ({ name: m.getName(), color: m.getBaseColorFactor().slice(0, 3).map((v) => +v.toFixed(3)) }));
    fs.writeFileSync(path.join(outDir, 'furniture', 'thumbs', `${name}.png`), await renderThumb(model.scaledTriangles()));
    entries[name] = { file: `furniture/${name}.glb`, thumb: `furniture/thumbs/${name}.png`, min: r(bounds.min), max: r(bounds.max), materials, original: true, exterior: true };
    console.log(`exterior ${name}: ${model.triangleCount()} triangles, ${(glb.length / 1024).toFixed(1)} KB`);
  }
  return entries;
}
